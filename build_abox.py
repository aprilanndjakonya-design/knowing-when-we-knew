def mdy(s: str) -> dt.date:
    return dt.datetime.strptime(s, "%m/%d/%Y").date()


def lit_ts(d: dt.date, rounded_day: bool = True) -> str:
    """Дата дневной точности → последний момент этого дня в любом поясе (правило R10)."""
    return f'"{d.isoformat()}T23:59:59-12:00"^^xsd:dateTimeStamp' if rounded_day else f'"{d.isoformat()}T00:00:00Z"^^xsd:dateTimeStamp'


def grid_floor(d: dt.date, grid: str) -> str:
    """Опорный момент знания T' ≤ T для класса KnownAsOf: начало месяца/квартала/года (00:00:00Z) или сам день T.
    Округление ВНИЗ: проверка использует знание не позже T' — консервативно (утечки невозможны, часть доступного
    знания считается ещё неизвестным); число различных классов KnownAsOf — и время HermiT — падает с сеткой."""
    if grid == "none":
        return f"{d.isoformat()}T15:00:00Z"
    if grid == "month":
        g = d.replace(day=1)
    elif grid == "quarter":
        g = d.replace(month=3 * ((d.month - 1) // 3) + 1, day=1)
    elif grid == "year":
        g = d.replace(month=1, day=1)
    else:
        raise ValueError(grid)
    return f"{g.isoformat()}T00:00:00Z"


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def safe(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]+", "_", s)


class Abox:
    def __init__(self) -> None:
        self.parts: list[str] = [PREFIXES]
        self.instants: set[str] = set()
        self.products: dict[str, str] = {}
        self.known_as_of: dict[str, str] = {}
        self.label_sets: dict[str, list[str]] = {}  # set id → заявки (один SPL-набор может быть у нескольких заявок)
        self.counts = {"applications": 0, "label_sets": 0, "label_versions": 0, "change_records": 0,
                       "approvals": 0, "boxed_warnings": 0, "patients": 0, "prescriptions": 0, "checks": 0,
                       "known_as_of_classes": 0, "verified_sections": 0, "srlc_known_from_asserted": 0}

    def instant(self, d: dt.date) -> str:
        name = f"iatd:t_{d.isoformat()}"
        if name not in self.instants:
            self.instants.add(name)
            self.parts.append(f'{name} a owl:NamedIndividual , time:Instant ; time:inXSDDateTimeStamp "{d.isoformat()}T00:00:00Z"^^xsd:dateTimeStamp .\n')
        return name

    def product(self, rxcui: str, name: str | None, tty: str | None) -> str:
        iri = f"iatd:rxcui_{rxcui}"
        if iri not in self.products:
            self.products[iri] = name or rxcui
            label = esc(name or f"RxNorm {rxcui}")
            self.parts.append(
                f'{iri} a owl:NamedIndividual , iat:DrugProduct ;\n    rdfs:label "{label}"@en ;\n    iat:rxcui "{rxcui}" ;\n'
                + (f'    iat:rxnormTermType "{esc(tty)}" ;\n' if tty else "")
                + f'    skos:exactMatch <http://purl.bioontology.org/ontology/RXNORM/{rxcui}> ;\n'
                f'    dcterms:source <https://rxnav.nlm.nih.gov/REST/rxcui/{rxcui}/properties.json> .\n')
        return iri

    def known_as_of_class(self, ts: str) -> str:
        key = re.sub(r"[^0-9TZ]", "", ts)
        iri = f"iat:KnownAsOf_{key}"
        if iri not in self.known_as_of:
            self.known_as_of[iri] = ts
            self.counts["known_as_of_classes"] += 1
            self.parts.append(
                f'{iri} a owl:Class ;\n    rdfs:label "known as of {ts}"@en ;\n'
                f'    owl:equivalentClass [ a owl:Class ; owl:intersectionOf ( iat:TemporalKnowledgeRecord\n'
                f'        [ a owl:Restriction ; owl:onProperty iat:knownFrom ;\n'
                f'          owl:someValuesFrom [ a rdfs:Datatype ; owl:onDatatype xsd:dateTimeStamp ;\n'
                f'                               owl:withRestrictions ( [ xsd:maxInclusive "{ts}"^^xsd:dateTimeStamp ] ) ] ] ) ] .\n')
        return iri


def build(args) -> dict:
    dated = json.loads((EVIDENCE / "srlc_bw_list_dated.json").read_text(encoding="utf-8"))["rows"]
    bw_dir = EVIDENCE / "srlc_dailymed_bw"
    verif = {}
    vp = EVIDENCE / "carrier_verification.json"
    if vp.exists():
        for c in json.loads(vp.read_text(encoding="utf-8"))["checks"]:
            if c.get("verdict") in ("confirmed", "unchanged") and c.get("carrier_spl", {}).get("bw_section_present"):
                verif[(c["application"], c["setid"], c["carrier"]["spl_version"])] = c
    setid_rx = json.loads((EVIDENCE / "setid_rxcui.json").read_text(encoding="utf-8")) if (EVIDENCE / "setid_rxcui.json").exists() else {}
    rx_hist = json.loads((EVIDENCE / "rxcui_history.json").read_text(encoding="utf-8")) if (EVIDENCE / "rxcui_history.json").exists() else {}
    join = json.loads((EVIDENCE / "synthea_bw_join.json").read_text(encoding="utf-8")) if (EVIDENCE / "synthea_bw_join.json").exists() and not args.no_synthea else None
    syn_ing = json.loads((EVIDENCE / "synthea_rxcui_ingredients.json").read_text(encoding="utf-8")) if (EVIDENCE / "synthea_rxcui_ingredients.json").exists() else {}

    by_app: dict[str, dict] = {}
    for r in dated:
        key = f"{r['application_type']}{r['application_number']}"
        cur = by_app.get(key)
        if cur is None or mdy(r["supplement_date"]) > mdy(cur["supplement_date"]):
            by_app[key] = r
    apps = sorted(by_app)
    if args.apps:
        # Подмножество для подачи: сначала заявки из назначений Synthea (короткие окна), затем с подтверждённым
        # по XML носителем, затем остальные по алфавиту.
        case_apps = []
        if join:
            for c in sorted(join.get("hindsight_bias_cases", []), key=lambda c: (c["window_days"], c["start"])):
                if c["application"] not in case_apps:
                    case_apps.append(c["application"])
        verified_apps = sorted({k[0] for k in verif})
        order = {a: i for i, a in enumerate(case_apps + [a for a in verified_apps if a not in case_apps])}
        apps = sorted(apps, key=lambda a: (order.get(a, 10**6), a))[: args.apps]

    ab = Abox()
    records_by_app: dict[str, dict] = {}
    for app in apps:
        p = bw_dir / f"{app}.json"
        if not p.exists():
            continue
        a = json.loads(p.read_text(encoding="utf-8"))
        row = by_app[app]
        lab = next((l for l in a["labels"] if l["carrier_version"]), None)
        ab.counts["applications"] += 1
        drug = esc(row["drug_name"])
        ingredient = esc(row["active_ingredient"])
        # Boxed warning (одна на заявку)
        bw_iri = f"iatd:bw_{app}"
        ab.parts.append(f'{bw_iri} a owl:NamedIndividual , iat:BoxedWarning ;\n    rdfs:label "Boxed Warning of {drug} ({ingredient}), per FDA SrLC"@en ;\n'
                        f'    iat:concernsProduct ' + (" , ".join(ab.product(c, (rx_hist.get(c) or {}).get("name"), (rx_hist.get(c) or {}).get("tty")) for c in (setid_rx.get(lab["setid"], {}).get("rxcuis") if lab else []) or []) or "iatd:unknown_product") + " .\n")
        if not lab or "iatd:unknown_product" in ab.parts[-1]:
            ab.parts[-1] = ab.parts[-1].replace(" ;\n    iat:concernsProduct iatd:unknown_product .\n", " .\n")
        ab.counts["boxed_warnings"] += 1
        # Дополнения (цепочка одобрений)
        prev_appr = None
        latest_sd = mdy(row["supplement_date"])
        db_updated = mdy(row["database_updated"])
        latest_any = mdy(row["latest_supplement_date_any_section"])
        recs = []
        for e in sorted(row["bw_supplements"], key=lambda e: mdy(e["date"])):
            d = mdy(e["date"])
            sid = safe(e["suppl"])
            appr = f"iatd:approval_{app}_{sid}"
            ab.parts.append(f'{appr} a owl:NamedIndividual , iat:LabelingSupplementApproval ;\n    rdfs:label "FDA approval of {app} {e["suppl"]}{" (Boxed Warning newly added)" if e["newly_added"] else " (Boxed Warning section changed)"}"@en ;\n    iat:occursAt {ab.instant(d)}' + (f' ;\n    obo:BFO_0000062 {prev_appr}' if prev_appr else "") + " .\n")
            prev_appr = appr
            ab.counts["approvals"] += 1
            vt = f"iatd:vt_srlc_{app}_{sid}"
            ab.parts.append(f'{vt} a owl:NamedIndividual , time:ProperInterval ; time:hasBeginning {ab.instant(d)} .\n')
            rec = f"iatd:srlc_{app}_{sid}"
            known = ""
            if d == latest_sd and latest_sd == latest_any:
                known = f'    iat:knownFrom {lit_ts(db_updated)} ;\n'
                ab.counts["srlc_known_from_asserted"] += 1
                avail_note = f"Availability: SrLC 'Database Updated' {row['database_updated']} (last update of this drug's entry; upper bound)."
            else:
                avail_note = "Availability time not stated: the SrLC page shows only the last update of the drug's entry; earlier entries are treated as not available (fail-closed)."
            ab.parts.append(
                f'{rec} a owl:NamedIndividual , iat:LabelingChangeRecord ;\n    rdfs:label "SrLC entry: {drug} {app} {e["suppl"]} ({e["date"]})"@en ;\n'
                f'    iat:supplementNumber "{esc(e["suppl"])}" ;\n    iat:describesEvent {appr} ;\n    iat:hasValidTime {vt} ;\n    iat:recordedIn iatd:src_fda_srlc ;\n'
                f'    iat:sourceDateText "{e["date"]}" ;\n{known}'
                + (f'    iat:approvesWarning {bw_iri} ;\n' if e["newly_added"] else "")
                + f'    dcterms:source <https://www.accessdata.fda.gov/scripts/cder/safetylabelingchanges/index.cfm?event=searchdetail.page&DrugNameID={row["drug_name_id"]}> ;\n'
                f'    iat:accessedOn "{ACCESSED}"^^xsd:date ;\n    rdfs:comment "Sections changed: {esc("; ".join(e["sections"]))}. {esc(avail_note)}"@en .\n')
            recs.append({"iri": rec, "known": db_updated if known else None, "date": d})
            ab.counts["change_records"] += 1
        # Этикетка DailyMed: набор + версия-носитель последнего BW-дополнения
        carrier_rec = None
        if lab:
            setid = lab["setid"]
            ls = f"iatd:labelset_{safe(setid)}"
            prods = [ab.product(c, (rx_hist.get(c) or {}).get("name"), (rx_hist.get(c) or {}).get("tty")) for c in setid_rx.get(setid, {}).get("rxcuis", [])]
            if setid in ab.label_sets:
                # Тот же SPL-набор уже описан по другой заявке: набор один (один документ), добавляем номер заявки;
                # версия-носитель ниже строится по заявке (IRI с номером заявки), чтобы записи знания не склеивались.
                ab.label_sets[setid].append(app)
                ab.parts.append(f'{ls} iat:applicationNumber "{app}" ;\n    rdfs:comment "Also listed in the FDA SrLC database under {app} ({esc(drug)}): one SPL set shared by several applications."@en .\n')
            else:
                ab.label_sets[setid] = [app]
                ab.parts.append(f'{ls} a owl:NamedIndividual , iat:LabelSet ;\n    rdfs:label "{esc(lab.get("title") or drug)} -- SPL set"@en ;\n    iat:splSetId "{setid}" ;\n    iat:applicationNumber "{app}" ;\n'
                                + (f'    iat:labelFor {" , ".join(prods)} ;\n' if prods else "")
                                + f'    dcterms:source <https://dailymed.nlm.nih.gov/dailymed/services/v2/spls/{setid}/history.json> ;\n    iat:accessedOn "{ACCESSED}"^^xsd:date ;\n'
                                f'    rdfs:comment "DailyMed history lists {len(lab["versions"])} published versions; the carrier of the latest Boxed Warning supplement is modelled."@en .\n')
                ab.counts["label_sets"] += 1
            cv = lab["carrier_version"]
            pub = dt.date.fromisoformat(cv["published_date"])
            lv = f"iatd:label_{safe(app)}_{safe(setid)}_v{cv['spl_version']}"
            vt = f"iatd:vt_{safe(app)}_{safe(setid)}_v{cv['spl_version']}"
            ab.parts.append(f'{vt} a owl:NamedIndividual , time:ProperInterval ; time:hasBeginning {ab.instant(latest_sd)} .\n')
            v = verif.get((app, setid, cv["spl_version"]))
            section = ""
            if v:
                section = f'    iat:containsBoxedWarningSection true ;\n    iat:includesWarning {bw_iri} ;\n'
                ab.counts["verified_sections"] += 1
                sec_note = f"Boxed Warning section (LOINC 34066-1) verified in the SPL XML ({v['verdict']})."
            else:
                sec_note = "Boxed Warning section presence not verified for this version (XML not fetched); the value of containsBoxedWarningSection is not asserted."
            ab.parts.append(
                f'{lv} a owl:NamedIndividual , iat:LabelVersion ;\n    rdfs:label "{drug} label, SPL version {cv["spl_version"]} (carrier of {app} {esc(row["supplement"])})"@en ;\n'
                f'    iat:versionOf {ls} ;\n    iat:splVersion {cv["spl_version"]} ;\n    iat:hasValidTime {vt} ;\n    iat:knownFrom {lit_ts(pub)} ;\n{section}'
                f'    iat:sourceDateText "Supplement approved {row["supplement_date"]}; DailyMed published_date {cv["published_date"]}" ;\n    iat:recordedIn iatd:src_dailymed ;\n'
                f'    dcterms:source <https://dailymed.nlm.nih.gov/dailymed/getFile.cfm?type=zip&setid={setid}&version={cv["spl_version"]}> ;\n    iat:accessedOn "{ACCESSED}"^^xsd:date ;\n'
                f'    rdfs:comment "Valid time begins at the FDA approval of the supplement it carries; the carrier is the first version published on or after that date (lower bound of the publication delay: {lab["lag_days_dailymed"]} days). {esc(sec_note)}"@en .\n')
            ab.counts["label_versions"] += 1
            carrier_rec = {"iri": lv, "known": pub, "date": latest_sd}
        records_by_app[app] = {"srlc": recs, "carrier": carrier_rec, "bw": bw_iri}

    # Synthea: назначения в окнах и проверки «на момент T»
    if join:
        patients: set[str] = set()
        cases = [c for c in join.get("hindsight_bias_cases", []) if c["application"] in records_by_app]
        # Сначала случаи с подтверждённым по XML носителем и коротким окном; не больше --max-cases
        verified_apps = {k[0] for k in verif}
        cases.sort(key=lambda c: (c["application"] not in verified_apps, c["window_days"], c["start"]))
        cases = cases[: args.max_cases]
        for i, case in enumerate(cases):
            app = case["application"]
            pid = f"iatd:patient_{safe(case['patient'])}"
            if pid not in patients:
                patients.add(pid)
                ab.parts.append(f'{pid} a owl:NamedIndividual , iat:SyntheticPatient ;\n    rdfs:label "Synthea patient {case["patient"]} (synthetic, no PHI)"@en .\n')
                ab.counts["patients"] += 1
            d = dt.date.fromisoformat(case["start"])
            T = f"{d.isoformat()}T15:00:00Z"          # момент проверки (evaluatedAsOf)
            Tg = grid_floor(d, args.t_grid)            # опорный момент знания (класс KnownAsOf) ≤ T
            Tg_dt = dt.datetime.fromisoformat(Tg.replace("Z", "+00:00"))
            code = case["code"]
            prod = ab.product(code, (syn_ing.get(code) or {}).get("name"), (syn_ing.get(code) or {}).get("tty"))
            rx = f"iatd:rx_{safe(case['patient'])}_{d.isoformat()}_{code}"
            rxrec = f"iatd:rxrec_{safe(case['patient'])}_{d.isoformat()}_{code}"
            vt = f"iatd:vt_{safe(case['patient'])}_{d.isoformat()}_{code}"
            ab.parts.append(f'{rx} a owl:NamedIndividual , iat:PrescriptionEvent ;\n    rdfs:label "{esc(case["drug"])} prescribed {d.isoformat()} (Synthea)"@en ;\n    iat:hasPatient {pid} ;\n    iat:prescribedProduct {prod} ;\n    iat:occursAt {ab.instant(d)} .\n')
            ab.parts.append(f'{vt} a owl:NamedIndividual , time:ProperInterval ; time:hasBeginning {ab.instant(d)} .\n')
            ab.parts.append(f'{rxrec} a owl:NamedIndividual , iat:PrescriptionRecord ;\n    rdfs:label "Prescription record {d.isoformat()} (synthetic EHR entry)"@en ;\n    iat:aboutPatient {pid} ;\n    iat:documentsEvent {rx} ;\n    iat:hasValidTime {vt} ;\n    iat:knownFrom "{T}"^^xsd:dateTimeStamp ;\n    iat:recordedIn iatd:src_synthetic_ehr .\n')
            ab.counts["prescriptions"] += 1
            # Какие записи были доступны на момент T (по нашим данным)
            # Точное T: запись назначения — тоже использованное знание (как в N1). На сетке опорный момент T' раньше
            # записи (она известна с T > T'), поэтому в usedRecord кладём только ВНЕШНЕЕ знание (SrLC, DailyMed);
            # само назначение связано с проверкой через checksPrescription и documentsEvent.
            known = [rxrec] if args.t_grid == "none" else []
            rb = records_by_app[app]
            for r in rb["srlc"]:
                if r["known"] and dt.datetime.combine(r["known"], dt.time(23, 59, 59), tzinfo=dt.timezone(dt.timedelta(hours=-12))) <= Tg_dt:
                    known.append(r["iri"])
            if rb["carrier"] and dt.datetime.combine(rb["carrier"]["known"], dt.time(23, 59, 59), tzinfo=dt.timezone(dt.timedelta(hours=-12))) <= Tg_dt:
                known.append(rb["carrier"]["iri"])
            cls = ab.known_as_of_class(Tg)
            chk = f"iatd:check_{safe(case['patient'])}_{d.isoformat()}_{code}"
            ab.parts.append(f'{chk} a owl:NamedIndividual , iat:AsOfSafetyCheck ,\n        [ a owl:Restriction ; owl:onProperty iat:usedRecord ; owl:allValuesFrom {cls} ] ;\n    rdfs:label "As-of safety check of the {d.isoformat()} prescription ({case["position_dailymed"]} / {case["position_srlc"]})"@en ;\n    iat:checksPrescription {rx} ;\n    iat:evaluatedAsOf "{T}"^^xsd:dateTimeStamp ;\n' + (f'    iat:usedRecord {" , ".join(known)} ;\n' if known else '') + f'    rdfs:comment "Approval {case["approval"]}; DailyMed carrier published {case["dailymed_available"]}; SrLC updated {case["srlc_updated"]}. Only records available at T are used; a static graph would also use the carrier label version."@en .\n')
            ab.counts["checks"] += 1
            if args.t_grid != "none":
                ab.parts.append(f'{chk} rdfs:comment "Knowledge cutoff for the DL guard is the reference instant {Tg} (grid: {args.t_grid}), rounded DOWN from the evaluation time {T}: records that became known between the two are treated as not yet known (conservative; no leakage possible). usedRecord lists external knowledge only; the prescription under evaluation is linked by checksPrescription."@en .\n')

    OUT.write_text("".join(ab.parts), encoding="utf-8")
    ab.counts["label_sets_shared"] = sum(1 for v in ab.label_sets.values() if len(v) > 1)
    ab.counts["t_grid"] = args.t_grid
    summary = {**ab.counts, "bytes": OUT.stat().st_size, "file": str(OUT), "generated_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
    (EVIDENCE / f"abox_summary_{OUT.stem.replace('its-about-time-data-', '')}.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False), encoding="utf-8")
    return summary


