"""Этап N2, шаг 6: модуль данных онтологии 0.2 (A-box) из собранных доказательств.

Источники (evidence/): srlc_bw_list_dated.json (BW-дополнения по заявкам), srlc_dailymed_bw/<APP>.json
(set id, версии, версия-носитель), carrier_verification.json (необязательно: раздел 34066-1 подтверждён по XML),
setid_rxcui.json + rxcui_history.json (необязательно: продукты RxNorm), synthea_bw_join.json (необязательно:
назначения в окнах «одобрено, но ещё не опубликовано»).

Что порождается на заявку (шаблоны — как у Copaxone в онтологии N1):
  - iat:LabelSet (set id, номер заявки, labelFor → продукты RxNorm, если известны);
  - iat:LabelVersion версии-носителя последнего BW-дополнения: valid time от даты одобрения (открытый конец),
    knownFrom = публикация в DailyMed (округление D T23:59:59-12:00, правило R10 N1);
    containsBoxedWarningSection утверждается ТОЛЬКО если подтверждено по XML — иначе значение не утверждается
    (открытый мир: кардинальность «ровно 1» не нарушена; закрытые правила помечают как «не проверено»);
  - iat:LabelingChangeRecord на каждое BW-дополнение заявки (с 2016): valid time от даты одобрения; knownFrom =
    «Database Updated» ТОЛЬКО для последнего дополнения заявки (колонка относится к последней записи), иначе
    время доступности не утверждается (fail-closed в запросах);
  - iat:LabelingSupplementApproval с цепочкой obo:BFO_0000062 (preceded by) по датам;
  - iat:BoxedWarning одна на заявку; approvesWarning — у дополнений с «Newly added», includesWarning — у носителя,
    если раздел подтверждён.
Назначения Synthea (если есть): пациент, PrescriptionRecord/Event, продукт по RxCUI, AsOfSafetyCheck с
ограничением usedRecord only KnownAsOf_T и классом KnownAsOf_T на каждое T.

Выход: ../solutions/grant-packages/NIH_ITS_ABOUT_TIME/ontology/its-about-time-data-0.2.ttl (+ summary JSON).
Запуск:  .venv/bin/python build_abox.py [--apps N] [--no-synthea]
"""
